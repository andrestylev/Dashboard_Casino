export function translate(message: string, locale: Locale): string {
  if (locale === "en") return message;
  const translated = translations[message];
  if (translated) return translated;
  const normalized = message.trim().replaceAll("_", " ");
  if (translations[normalized]) return translations[normalized];
  const caseInsensitiveMatch = Object.keys(translations).find(
    (key) => key.toLocaleLowerCase() === normalized.toLocaleLowerCase(),
  );
  return caseInsensitiveMatch ? translations[caseInsensitiveMatch] : message;
}

export function getInitialLocale(): Locale {
  const saved = localStorage.getItem("casino-dashboard-locale");
  if (saved === "en" || saved === "es") return saved;
  return navigator.language.toLowerCase().startsWith("es") ? "es" : "en";
}

export function getInitialTheme(): ThemeMode {
  const saved = localStorage.getItem("casino-dashboard-theme");
  return saved === "light" || saved === "dark" ? saved : "system";
}

export function systemTheme(): "light" | "dark" {
  return window.matchMedia("(prefers-color-scheme: dark)").matches ? "dark" : "light";
}

export function initializePreferences() {
  const locale = getInitialLocale();
  const theme = getInitialTheme();
  document.documentElement.lang = locale;
  document.documentElement.dataset.theme = theme === "system" ? systemTheme() : theme;
  document.documentElement.style.colorScheme = document.documentElement.dataset.theme ?? "light";
}
