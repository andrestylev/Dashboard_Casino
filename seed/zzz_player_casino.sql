CREATE TABLE IF NOT EXISTS player_chip_wallets (
    player_id bigint NOT NULL PRIMARY KEY
        REFERENCES players (id) ON DELETE CASCADE,
    balance bigint DEFAULT 0 NOT NULL,
    updated_at timestamp with time zone DEFAULT now() NOT NULL,
    CONSTRAINT ck_player_chip_wallets_balance_in_chip_range
        CHECK (balance >= 0 AND balance <= 10000000)
);

CREATE TABLE IF NOT EXISTS player_chip_entries (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    player_id bigint NOT NULL REFERENCES players (id) ON DELETE CASCADE,
    delta bigint NOT NULL,
    reason varchar(30) NOT NULL,
    round_id uuid REFERENCES demo_game_rounds (id) ON DELETE SET NULL,
    created_at timestamp with time zone DEFAULT now() NOT NULL,
    CONSTRAINT ck_player_chip_entries_delta_nonzero CHECK (delta <> 0),
    CONSTRAINT ck_player_chip_entries_reason_allowed
        CHECK (reason IN ('migration', 'chip_purchase', 'wager', 'payout', 'refund'))
);
CREATE INDEX IF NOT EXISTS ix_player_chip_entries_player_created
    ON player_chip_entries (player_id, created_at);

CREATE TABLE IF NOT EXISTS player_vip_subscriptions (
    player_id bigint NOT NULL PRIMARY KEY REFERENCES players (id) ON DELETE CASCADE,
    tier varchar(8) NOT NULL,
    started_at timestamp with time zone NOT NULL,
    expires_at timestamp with time zone NOT NULL,
    amount numeric(12, 2) NOT NULL,
    updated_at timestamp with time zone DEFAULT now() NOT NULL,
    CONSTRAINT ck_player_vip_subscriptions_vip_subscription_tier
        CHECK (tier IN ('standard', 'silver', 'gold', 'platinum', 'diamond')),
    CONSTRAINT ck_player_vip_subscriptions_paid_tier_only
        CHECK (tier <> 'standard'),
    CONSTRAINT ck_player_vip_subscriptions_amount_positive CHECK (amount > 0),
    CONSTRAINT ck_player_vip_subscriptions_expires_after_started
        CHECK (expires_at > started_at)
);

INSERT INTO wallets (player_id, balance)
SELECT id, 0 FROM players
ON CONFLICT (player_id) DO NOTHING;

INSERT INTO player_chip_wallets (player_id, balance)
SELECT p.id, COALESCE(d.balance, 0)
FROM players AS p
LEFT JOIN demo_credit_wallets AS d ON d.player_id = p.id
ON CONFLICT (player_id) DO NOTHING;

INSERT INTO player_chip_entries (player_id, delta, reason)
SELECT d.player_id, d.balance, 'migration'
FROM demo_credit_wallets AS d
WHERE d.balance > 0
  AND NOT EXISTS (
      SELECT 1 FROM player_chip_entries AS e
      WHERE e.player_id = d.player_id AND e.reason = 'migration'
  );

