CREATE TABLE IF NOT EXISTS player_credentials (
    player_id bigint NOT NULL PRIMARY KEY
        REFERENCES players (id) ON DELETE CASCADE,
    password_hash varchar(255) NOT NULL,
    failed_login_attempts integer DEFAULT 0 NOT NULL,
    locked_until timestamp with time zone,
    last_login_at timestamp with time zone,
    created_at timestamp with time zone DEFAULT now() NOT NULL,
    CONSTRAINT ck_player_credentials_failed_attempts_non_negative
        CHECK (failed_login_attempts >= 0)
);

CREATE TABLE IF NOT EXISTS player_sessions (
    id uuid DEFAULT gen_random_uuid() NOT NULL PRIMARY KEY,
    player_id bigint NOT NULL REFERENCES players (id) ON DELETE CASCADE,
    token_hash varchar(64) NOT NULL UNIQUE,
    created_at timestamp with time zone DEFAULT now() NOT NULL,
    expires_at timestamp with time zone NOT NULL,
    revoked_at timestamp with time zone,
    ip_address inet,
    user_agent varchar(255),
    CONSTRAINT ck_player_sessions_expires_after_created
        CHECK (expires_at > created_at)
);
CREATE INDEX IF NOT EXISTS ix_player_sessions_player_id ON player_sessions (player_id);

CREATE TABLE IF NOT EXISTS demo_credit_wallets (
    player_id bigint NOT NULL PRIMARY KEY REFERENCES players (id) ON DELETE CASCADE,
    balance integer DEFAULT 1000 NOT NULL,
    last_refilled_on date NOT NULL,
    updated_at timestamp with time zone DEFAULT now() NOT NULL,
    CONSTRAINT ck_demo_credit_wallets_balance_in_demo_range
        CHECK (balance >= 0 AND balance <= 1000)
);

CREATE TABLE IF NOT EXISTS demo_game_rounds (
    id uuid DEFAULT gen_random_uuid() NOT NULL PRIMARY KEY,
    player_id bigint NOT NULL REFERENCES players (id) ON DELETE CASCADE,
    game_code varchar(20) NOT NULL,
    status varchar(20) DEFAULT 'in_progress' NOT NULL,
    stake integer NOT NULL,
    state jsonb NOT NULL,
    outcome jsonb,
    created_at timestamp with time zone DEFAULT now() NOT NULL,
    updated_at timestamp with time zone DEFAULT now() NOT NULL,
    completed_at timestamp with time zone,
    CONSTRAINT ck_demo_game_rounds_game_code_allowed
        CHECK (game_code IN ('slots', 'blackjack', 'roulette')),
    CONSTRAINT ck_demo_game_rounds_status_allowed
        CHECK (status IN ('in_progress', 'completed', 'voided')),
    CONSTRAINT ck_demo_game_rounds_stake_in_demo_range
        CHECK (stake BETWEEN 10 AND 100)
);
CREATE INDEX IF NOT EXISTS ix_demo_game_rounds_player_created
    ON demo_game_rounds (player_id, created_at);
CREATE UNIQUE INDEX IF NOT EXISTS uq_demo_game_rounds_player_active_blackjack
    ON demo_game_rounds (player_id)
    WHERE game_code = 'blackjack' AND status = 'in_progress';

CREATE TABLE IF NOT EXISTS demo_credit_entries (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    player_id bigint NOT NULL REFERENCES players (id) ON DELETE CASCADE,
    delta integer NOT NULL,
    reason varchar(30) NOT NULL,
    round_id uuid REFERENCES demo_game_rounds (id) ON DELETE SET NULL,
    created_at timestamp with time zone DEFAULT now() NOT NULL,
    CONSTRAINT ck_demo_credit_entries_delta_nonzero CHECK (delta <> 0),
    CONSTRAINT ck_demo_credit_entries_reason_allowed
        CHECK (reason IN ('initial_credit', 'daily_refill', 'wager', 'payout', 'refund'))
);
CREATE INDEX IF NOT EXISTS ix_demo_credit_entries_player_created
    ON demo_credit_entries (player_id, created_at);

